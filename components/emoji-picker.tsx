// Frequently used emojis for quick access
const FREQUENT_EMOJIS = ['⭐', '🌟', '✨', '🎯', '🏆', '🥇', '💪', '📚', '🎮', '📱', '🏠', '🍎', '💰', '🎁', '✅', '❤️', '👍', '🔥', '⚡', '🧹', '🛏️', '🦷', '🥗', '📖', '✏️', '🎨', '🎵', '🏃', '🧘', '💤']

interface EmojiPickerProps {
  value: string
  onChange: (emoji: string) => void
  onClose?: () => void
}

export function EmojiPicker({ value, onChange, onClose }: EmojiPickerProps) {
  const [searchQuery, setSearchQuery] = useState('')
  const [selectedCategory, setSelectedCategory] = useState<string>('Frequent')

  const filteredEmojis = searchQuery
    ? Object.values(EMOJI_CATEGORIES).flat().filter(emoji => 
        emoji.toLowerCase().includes(searchQuery.toLowerCase())
      )
    : selectedCategory === 'Frequent'
      ? FREQUENT_EMOJIS
      : EMOJI_CATEGORIES[selectedCategory as keyof typeof EMOJI_CATEGORIES] || []

  const handleSelect = (emoji: string) => {
    onChange(emoji)
    onClose?.()
  }

  return (
    <div className="bg-white rounded-xl border border-slate-200 shadow-xl w-full max-w-sm overflow-hidden">
      {/* Header */}
      <div className="flex items-center justify-between p-3 border-b border-slate-100">
        <h3 className="font-semibold text-slate-900">Select Icon</h3>
        {onClose && (
          <Button variant="ghost" size="icon" onClick={onClose} className="h-8 w-8">
            <X className="h-4 w-4" />
          </Button>
        )}
      </div>

      {/* Search */}
      <div className="p-3 border-b border-slate-100">
        <div className="relative">
          <Search className="absolute left-3 top-1/2 -translate-y-1/2 h-4 w-4 text-slate-400" />
          <Input
            placeholder="Search emojis..."
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            className="pl-9 h-9"
          />
        </div>
      </div>

      {/* Category Tabs */}
      {!searchQuery && (
        <div className="flex gap-1 p-2 overflow-x-auto border-b border-slate-100 scrollbar-hide">
          <Button
            variant={selectedCategory === 'Frequent' ? 'default' : 'ghost'}
            size="sm"
            onClick={() => setSelectedCategory('Frequent')}
            className="h-7 px-2 text-xs flex-shrink-0"
          >
            ⭐ Frequent
          </Button>
          {Object.keys(EMOJI_CATEGORIES).map((category) => (
            <Button
              key={category}
              variant={selectedCategory === category ? 'default' : 'ghost'}
              size="sm"
              onClick={() => setSelectedCategory(category)}
              className="h-7 px-2 text-xs flex-shrink-0 whitespace-nowrap"
            >
              {category}
            </Button>
          ))}
        </div>
      )}

      {/* Emoji Grid */}
      <div className="p-3 h-64 overflow-y-auto">
        <div className="grid grid-cols-8 gap-1">
          {filteredEmojis.map((emoji, index) => (
            <button
              key={`${emoji}-${index}`}
              onClick={() => handleSelect(emoji)}
              className={cn(
                'w-9 h-9 flex items-center justify-center text-xl rounded-lg transition-all hover:bg-slate-100 active:scale-90',
                value === emoji && 'bg-blue-100 ring-2 ring-blue-500'
              )}
            >
              {emoji}
            </button>
          ))}
        </div>
        {filteredEmojis.length === 0 && (
          <div className="flex items-center justify-center h-full text-slate-500 text-sm">
            No emojis found
          </div>
        )}
      </div>

      {/* Selected Preview */}
      {value && (
        <div className="p-3 border-t border-slate-100 flex items-center gap-3">
          <span className="text-3xl">{value}</span>
          <span className="text-sm text-slate-600">Selected icon</span>
        </div>
      )}
    </div>
  )
}

// Compact trigger button that opens the picker
interface EmojiPickerTriggerProps {
  value: string
  onChange: (emoji: string) => void
  className?: string
}

export function EmojiPickerTrigger({ value, onChange, className }: EmojiPickerTriggerProps) {
  const [isOpen, setIsOpen] = useState(false)

  return (
    <div className={cn('relative', className)}>
      <button
        type="button"
        onClick={() => setIsOpen(!isOpen)}
        className="w-full h-10 px-3 flex items-center gap-2 rounded-md border border-slate-200 bg-white hover:bg-slate-50 transition-colors text-left"
      >
        <span className="text-2xl">{value || '😀'}</span>
        <span className="text-sm text-slate-500 flex-1">
          {value ? 'Click to change' : 'Select an icon'}
        </span>
      </button>
      
      {isOpen && (
        <>
          {/* Backdrop */}
          <div 
            className="fixed inset-0 z-40" 
            onClick={() => setIsOpen(false)}
          />
          {/* Picker */}
          <div className="absolute z-50 mt-2 left-0 right-0">
            <EmojiPicker
              value={value}
              onChange={(emoji) => {
                onChange(emoji)
                setIsOpen(false)
              }}
              onClose={() => setIsOpen(false)}
            />
          </div>
        </>
      )}
    </div>
  )
}
